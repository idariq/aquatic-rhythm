/**
 * Round-trip sync check: regenerates all localized article HTML from
 * translations/<lang>/*.json and fails if the result differs from what's
 * committed on disk.
 *
 * This is the guard against the failure mode discovered 2026-08-17: HTML
 * under id/ja/articles/ got hand-edited directly (naturalness fixes,
 * de-jargoning, completeness fixes) across several PRs while
 * translations/*.json — the actual source build-i18n.mjs reads from — was
 * never updated to match. The drift was invisible until someone ran the
 * generator again, at which point it would have silently overwritten
 * months of hand-editing with stale JSON content.
 *
 * Usage:
 *   node scripts/check-i18n-sync.mjs
 *
 * Exit code 0 = in sync. Exit code 1 = drift detected (details printed).
 */
import { execSync } from 'child_process';
import path from 'path';

const ROOT = path.join(import.meta.dirname, '..');
const WATCHED_DIRS = ['id/articles', 'ja/articles'];

function run(cmd) {
  return execSync(cmd, { cwd: ROOT, encoding: 'utf8' });
}

// Regenerate every localized article from its translations/*.json source.
// This mutates the working tree in place — safe in CI (ephemeral checkout)
// and locally (only rewrites files to match their own JSON source; if this
// changes anything, that's exactly the drift being checked for).
try {
  run('node scripts/build-i18n.mjs --all');
} catch (e) {
  console.error('i18n:check — build-i18n.mjs failed to run:');
  console.error(e.stdout || e.message);
  process.exit(1);
}

let diffStat = '';
let clean = true;
try {
  run(`git diff --quiet -- ${WATCHED_DIRS.join(' ')}`);
} catch {
  clean = false;
  diffStat = run(`git diff --stat -- ${WATCHED_DIRS.join(' ')}`);
}

if (clean) {
  console.log('i18n:check — translations/*.json and generated HTML are in sync.');
  process.exit(0);
}

console.error('i18n:check FAILED — translations/*.json and the generated HTML are out of sync.\n');
console.error('Regenerating HTML from the current translations/*.json produced different output');
console.error('than what is committed. This means either:\n');
console.error('  (a) the localized HTML was hand-edited directly without updating the source JSON, or');
console.error('  (b) translations/*.json was edited but the HTML was never rebuilt.\n');
console.error('To fix:');
console.error('  - If you edited HTML directly: run `npm run i18n:extract` to pull your changes back');
console.error('    into translations/*.json, then `npm run i18n:check` again to confirm a clean');
console.error('    round-trip, and commit both the JSON and the (possibly further-adjusted) HTML.');
console.error('  - If you edited translations/*.json: the HTML has already been regenerated by this');
console.error('    check — review the diff below and commit it.\n');
console.error(diffStat);
process.exit(1);
